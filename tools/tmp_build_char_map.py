# ── Main matching logic ────────────────────────────────────────────────
def find_font_bank():
    """Find the CHR bank+ptable whose tiles best match the katakana reference set."""
    best = None
    best_score = 0
    for bank in range(32):
        d = load_chr(bank)
        for pt in range(4):
            base = pt * 2048
            score = 0
            for tile_idx in range(0x04, 0x39):
                bm = tile_fp(d, base, tile_idx)
                if px_count(bm) < 6:
                    continue
                best_ref_match = 0
                for ch, ref_bm in REF.items():
                    m = bm_match(bm, ref_bm)
                    if m > best_ref_match:
                        best_ref_match = m
                score += best_ref_match
            if score > best_score:
                best_score = score
                best = (bank, pt, score)
    return best

def match_tile(bm, threshold=48):
    """Match a bitmap against reference set. Return (char, score) or None."""
    best_ch = None
    best_m = 0
    for ch, ref_bm in REF.items():
        m = bm_match(bm, ref_bm)
        if m > best_m:
            best_m = m
            best_ch = ch
    if best_m >= threshold:
        return best_ch, best_m
    return None, best_m

def match_digit(bm, threshold=48):
    best_d = None
    best_m = 0
    for d, ref_bm in REF_D.items():
        m = bm_match(bm, ref_bm)
        if m > best_m:
            best_m = m
            best_d = d
    if best_m >= threshold:
        return best_d, best_m
    return None, best_m

def build_mapping_from_bank(bank, pt):
    """Build code→char mapping for all tiles in the given pattern table."""
    d = load_chr(bank)
    base = pt * 2048
    mapping = {}
    # Kana range $04-$38
    for tile_idx in range(0x04, 0x39):
        bm = tile_fp(d, base, tile_idx)
        if px_count(bm) < 6:
            continue
        ch, score = match_tile(bm)
        if ch:
            mapping[tile_idx] = (ch, score)
    # Digit range $76-$7F
    for tile_idx in range(0x76, 0x80):
        bm = tile_fp(d, base, tile_idx)
        if px_count(bm) < 6:
            continue
        dg, score = match_digit(bm)
        if dg:
            mapping[tile_idx] = (dg, score)
    return mapping

def main():
    print("=== Finding best font bank ===")
    result = find_font_bank()
    if result:
        bank, pt, score = result
        print(f"Best: chr_{bank:02x} ptable {pt} (${pt*2048:04X}), score={score}")
    else:
        print("No suitable bank found!")
        return

    print(f"\n=== Building tile→char mapping for chr_{bank:02x} ptable {pt} ===")
    mapping = build_mapping_from_bank(bank, pt)

    # Print the mapping
    print(f"\n--- Kana tile mapping (chr_{bank:02x} ptable {pt}) ---")
    for code in sorted(mapping.keys()):
        if code < 0x76:
            ch, score = mapping[code]
            print(f"  ${code:02X} → {ch} (match={score}/64)")

    print(f"\n--- Digit tile mapping ---")
    for code in sorted(mapping.keys()):
        if code >= 0x76:
            ch, score = mapping[code]
            print(f"  ${code:02X} → {ch} (match={score}/64)")

    # ── Cross-validate with officer names ──
    print(f"\n=== Cross-validating with officer names ===")
    names = get_officer_names(50)
    for i in sorted(KNOWN_OFFICERS.keys()):
        if i >= len(names):
            break
        byte_seq = names[i]
        reading = KNOWN_OFFICERS[i]
        decoded = []
        for b in byte_seq:
            if b in mapping:
                ch, _ = mapping[b]
                decoded.append(ch)
            else:
                decoded.append(f"?{b:02X}")
        decoded_str = "".join(decoded)
        match = "✓" if decoded_str == reading else "✗"
        hex_str = " ".join(f"{b:02X}" for b in byte_seq)
        print(f"  [{match}] Officer {i:2d}: [{hex_str}]")
        print(f"       decoded: {decoded_str}")
        print(f"       expected: {reading}")

if __name__ == "__main__":
    main()
