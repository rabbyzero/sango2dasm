CHR_DIR = "rom/chr"
PRG_DIR = "rom/prg"

def load_prg(bank):
    with open(os.path.join(PRG_DIR, f"prg_{bank:02x}.bin"), "rb") as f:
        return f.read()

def load_chr(bank):
    with open(os.path.join(CHR_DIR, f"chr_{bank:02x}.bin"), "rb") as f:
        d = f.read()
    if len(d) < 8192:
        d += b"\x00" * (8192 - len(d))
    return d

# ── Officer name table ────────────────────────────────────────────────────
def get_officer_names(n=50):
    d = load_prg(0x10)
    names = []
    off = 0x101A
    for _ in range(400):
        e = d[off:off + 10]
        nb = []
        for b in e:
            if b == 0: break
            nb.append(b)
        if nb:
            names.append(nb)
        off += 10
    return names[:n]

