# ── Tile fingerprint ────────────────────────────────────────────────────
def tile_fp(data, base, tile_idx):
    """Return combined-OR bitmap (8 bytes) for a tile."""
    off = base + tile_idx * 16
    t = data[off:off + 16]
    return bytes(t[r] | t[r + 8] for r in range(8))

def px_count(bm):
    return sum(bin(b).count('1') for b in bm)

def h_sym(bm):
    """Horizontal symmetry score (0-8)."""
    s = 0
    for b in bm:
        rev = int(f"{b:08b}"[::-1], 2)
        if b == rev:
            s += 1
    return s

def v_sym(bm):
    """Vertical symmetry score (0-4)."""
    s = 0
    for i in range(4):
        if bm[i] == bm[7 - i]:
            s += 1
    return s

def bm_match(a, b):
    """Pixel-level match (0-64)."""
    return sum(8 - bin(x ^ y).count('1') for x, y in zip(a, b))

