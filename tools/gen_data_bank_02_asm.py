#!/usr/bin/env python3
"""Render PRG bank $02 (the Namco-163 sound/note data bank) as annotated asm.

Bank $02 is pure data: it is mapped into the $8000-$9FFF window by SwitchBank8
and read by B1F_SoundNotePlayer ($E609, fixed bank $1F), which does
`LDY #$22 ; JSR SwitchBank8_B` (Y & $1F = $02) and then loads the 4-byte note
entry at $8000 + soundID*4. The per-frame player is B0E/B0F
BattleAnimSoundEngine ($D8D4) + BattleSoundChannelProc ($DC59). See
asm/banks/prg_1f_boot.asm and code/bank_switch_map.md (sections 3, 4.1, 5.2).

Layout (format proof and cell semantics: tools/sound_streams.py):

  $8000-$82DF  SoundNoteHeaderTable  - 184 x 4-byte entries (index = soundID);
                 the last 2 bytes of every entry are a 16-bit stream pointer
                 (b2 = low, b3 stored by the player as b3 + $40 = high)
  $82E0-$9FFF  SoundCommandStreams   - note records + 2-byte command cells,
                 flush-packed; the tail runs on into bank $03 $8000-$8965,
                 which data_03_terrain.asm decodes (SoundStream_B03_*).

Entry $B7's pointer ($4010) is never followed; its 4 bytes at $82DC are the
note that 17 entries' pointers target, so this file emits its $FF terminator
($82E0) appended to that table row and the stream labels start at $82E1.

Usage:
    python tools/gen_data_bank_02_asm.py            # preview on stdout
    python tools/gen_data_bank_02_asm.py --write    # update asm/banks/data_02_sound.asm
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sound_streams as ss          # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BANK = 0x02
BANK_BIN = os.path.join('rom', 'prg', 'prg_%02x.bin' % BANK)
from bank_asm_names import data_asm_path               # noqa: E402
ASM_PATH = data_asm_path(BANK, ROOT)

WINDOW_CPU = 0x8000          # bank $02 is only ever mapped into $8000-$9FFF
BANK_SIZE = 0x2000           # 8 KB
ENTRY_SIZE = ss.DESC_SIZE
HEADER_CPU = 0x8000          # first note entry
HEADER_COUNT = ss.DESC_COUNT  # 184 entries, soundID $00-$B7
STREAM_CPU = 0x82E0          # first byte of the SoundCommandStreams region
TRACK_STRIDE = ss.TRACK_STRIDE
TRACK_COUNT = 11             # $0700 + 11*22 = $0F2, the SoundInit clear bound
STREAM_PTR_BIAS = ss.PTR_HIGH_BIAS
ROW_BYTES = 16               # .byte bytes per line (matches data_03_terrain.asm)
COMMENT_COL = 88

BANNER = """\
;===============================================================================
; DATA Bank 02 (PRG $02) - 8KB sound/note data bank, mapped into $8000-$9FFF by
; SwitchBank8; no code lives here (see code/bank_switch_map.md 5.2).
;
; GENERATED by tools/gen_data_bank_02_asm.py --write; byte-exactness is enforced
; by tools/verify_data_bank_02.py. Raw source: rom/prg/prg_02.bin (read-only),
; plus rom/prg/prg_03.bin for the stream tail that runs past $9FFF.
;
; The SoundNoteHeaderTable is the overall header: 184 entries x 4 bytes at
; $8000+soundID*4, read by B1F_SoundNotePlayer ($E609, fixed bank $1F) via
;   LDY #$22 ; JSR SwitchBank8_B     (Y & $1F = $02 -> this bank at $8000)
; The last 2 bytes of every entry are one 16-bit stream pointer: b2 = low byte,
; b3 is stored at $0703,X as b3 + $40 (high byte). b0 selects the sound-RAM
; track slot (X = b0, stride $16, 11 tracks at $0700), b1 the hardware channel
; 0-7 (0-3 = APU pulse1/pulse2/triangle/noise, 4-7 = Namco-163); on a retrigger
; of a busy track the player mutes that track's PREVIOUS APU channel through
; $4015 (SoundChannelTable $E667 = all-channels-except-ch masks). The wrapper
; chain B1F_SoundWrapper0..F ($E66B-$E6A5) plays a soundID then falls through
; with soundID+1, so a fanfare/melody is a contiguous run of entries.
;
; Regions:
;   $8000-$82DB  SoundNoteHeaderTable  (rows $00-$B6 of the 184-entry table)
;   $82DC-$9FFF  SoundCommandStreams   (starts on entry $B7's row - see below)
;
; The stream pointer is a complete CPU address and the driver maps two windows
; while playing (prg_0e_0f_battle.asm $D8D4-$D8E0: bank $02 at $8000 AND bank $03 at
; $A000 via LDA #$23 / ORA #$C0 / STA NAMCO_PRG_A000). Stream high bytes run
; $82-$A8, so soundIDs $A4-$B6 play out of bank $03: the sound area is bank $02
; $82DC-$9FFF followed by bank $03 $8000-$8965, with no gaps in between; the
; bank $03 half is decoded in asm/banks/data_03_terrain.asm (SoundStream_B03_*).
;
; Sound cell legend (decoder + coverage proof: tools/sound_streams.py):
;   4-byte stream header [tick][duty][control][sweep], then 2-byte cells
;   [opcode][operand] - "C#4/16" = pitch/sustain ticks (pulse reference pitch:
;   the triangle channel sounds 3 octaves higher and the 163 channels read
;   their own divisor rows, noise takes the opcode as a raw period, and a low
;   nibble of $C-$F is "rest/N"), "mark" = $FD loop point, "goto cN"/
;   "loop cN xK" = jump to cell N, "trem dD pP"/"env+n/p" = volume envelope,
;   "ctrl/sweep/duty/vib/tick" = channel setup, and $FF ends the stream without
;   consuming its operand byte (the area is packed).
;   Cell numbers (cN) are the driver's "state": one per cell; jump operands are
;   given in those units. Header b0 bits0-3 = frames per tick - 1, bit7 = second
;   NoteFreqTable row; b1 = duty source (only read via $A2); b2 = channel
;   control byte for $4000/$4004/$4008/$400C (bits0-3 volume, bit4 envelope,
;   bits6-7 duty); b3 = sweep byte for $4001+channel.
;
; 166 streams cover $82DC-$A965 exactly: every one ends at $FF and every gap
; between consecutive stream addresses equals the parsed length.
;===============================================================================

.segment "CODE_BANK02"
"""


def read_bank():
    with open(os.path.join(ROOT, BANK_BIN), 'rb') as f:
        return f.read()


def _hex(v):
    return '$%02X' % v if v < 0x100 else '$%04X' % v


def fmt_entry(i, b):
    """One 4-byte header entry as a .byte line with the decoded fields."""
    b0, b1, b2, b3 = b
    cpu = HEADER_CPU + i * ENTRY_SIZE
    ptr = (((b3 + STREAM_PTR_BIAS) << 8) | b2) & 0xFFFF
    trk = 'trk %d' % (b0 // TRACK_STRIDE) if b0 % TRACK_STRIDE == 0 \
        and b0 < TRACK_STRIDE * TRACK_COUNT else 'trk ?'
    body = '  .byte ' + ', '.join('$%02X' % x for x in b)
    return '%s%s; $%04X  ID %s  %s  ch %s %-8s ptr %s' % (
        body, ' ' * max(1, 31 - len(body)), cpu, _hex(i), trk, _hex(b1),
        ss.CH_NAME[b1 & 7], _hex(ptr))


def stream_label(ids):
    return 'SoundStream_B02_Snd%02X' % min(ids)


def block_comment(desc, cells, hdr, end):
    """The ; --- $ADDR-$ADDR ... --- header lines of one stream."""
    ids = desc['ids']
    tick = (hdr[0] & 0x0F) + ss.TICK_BASE
    pitch = [c for c in cells if c['op'] < 0xA0]
    loops = [c for c in cells if 0xB0 <= c['op'] <= 0xBF]
    marks = [c for c in cells if c['op'] == 0xFD]
    length = sum(c['arg'] for c in pitch) * tick
    span = 'soundID %s' % _hex(ids[0]) if len(ids) == 1 \
        else 'soundIDs %s' % ' '.join(_hex(i) for i in ids)
    out = ['; --- %s-%s  %s %s (track %s) command stream: %d cell%s, %d frame%s/cell, '
           'header %s; descriptor b2/b3 -> %s ---'
           % (_hex(desc['addr']), _hex(end - 1), span, desc['ch_name'], desc['track'],
              len(cells), '' if len(cells) == 1 else 's', tick,
              '' if tick == 1 else 's',
              ' '.join('$%02X' % x for x in hdr), _hex(desc['addr']))]
    extra = []
    if len(ids) > 1:
        extra.append('also targeted by %s' %
                     ' '.join(_hex(i) for i in ids[1:]))
    if not pitch:
        extra.append('no pitch cells: this note silences the track')
    if marks:
        extra.append('%d loop marker(s)' % len(marks))
    if loops:
        extra.append('%d jump/loop cell(s)' % len(loops))
    if pitch:
        extra.append('%d notes, %.1f s single pass' % (len(pitch), length / 60.0))
    if end > ss.STREAM_B02_END:
        tail = end - ss.STREAM_B02_END
        extra.append('cells continue in data_03_terrain.asm $8000-$%04X' % (0x8000 + tail - 1))
    if extra:
        out.append(';     ' + ', '.join(extra))
    return out


def emit_stream(sd, desc, lo, hi):
    """asm lines for one stream, clipped to the [lo, hi) byte range of bank $02."""
    addr = desc['addr']
    cells, hdr, end, problems = ss.walk(sd, addr, desc['channel'])
    lines = block_comment(desc, cells, hdr, end)
    if problems:
        lines.append('; UNDECODED: %s' % problems)
    lines.append('%s:' % stream_label(desc['ids']))
    items = [(4, 'hdr %s tick %d' % (' '.join('$%02X' % x for x in hdr),
                                     (hdr[0] & 0x0F) + ss.TICK_BASE))]
    items += [(c['size'], c['tag']) for c in cells]
    chan = 'snd %s %-8s' % (_hex(desc['ids'][0]), desc['ch_name'])
    rows, a, row, row_bytes = [], addr, [], 0
    for k, (n, tag) in enumerate(items):
        last = k == len(items) - 1
        if row and (a + row_bytes >= hi or
                    (row_bytes + n > ROW_BYTES and not last)):
            rows.append((a, row))
            a += row_bytes
            row, row_bytes = [], 0
        if a + row_bytes >= hi:
            break                       # rest of the stream lives in bank $03
        row.append((n, tag))
        row_bytes += n
    if row:
        rows.append((a, row))
    for start, items_row in rows:
        nbytes = sum(x[0] for x in items_row)
        vals = [sd.read(start + k) for k in range(nbytes)]
        body = '  .byte ' + ', '.join('$%02X' % x for x in vals)
        tag = ' | '.join(t for _, t in items_row)
        lines.append('%s%s; %s %s  %s' % (body, ' ' * max(1, COMMENT_COL - len(body)),
                                          _hex(start), chan, tag))
    if rows and rows[-1][0] + sum(x[0] for x in rows[-1][1]) < end:
        rest = end - (rows[-1][0] + sum(x[0] for x in rows[-1][1]))
        lines.append('  ; %s-%s: the remaining %d bytes are bank $03 data '
                     '(data_03_terrain.asm $8000-$%04X)'
                     % (_hex(ss.STREAM_B02_END), _hex(end - 1), rest,
                        0x8000 + rest - 1))
    return lines


def cell_tag(c):
    return c['tag']


def render(data):
    sd = ss.SoundData(b02=data)
    out = [BANNER.rstrip('\n'), '']
    out.append('; --- $8000-$82DB  SoundNoteHeaderTable rows $00-$B6 (the table defines'
               ' %d entries x %d bytes, index = soundID); b2/b3 = 16-bit stream'
               ' pointer, b3 +$40 ---' % (HEADER_COUNT, ENTRY_SIZE))
    out.append('SoundNoteHeaderTable:')
    for i in range(HEADER_COUNT - 1):
        out.append(fmt_entry(i, data[i * ENTRY_SIZE:i * ENTRY_SIZE + ENTRY_SIZE]))
    out.append('')
    out.append('; --- $82DC-$9FFF  SoundCommandStreams: note records + 2-byte command')
    out.append(';     cells, packed back to back; the final stream runs on into bank $03')
    out.append(';     (coverage proof: python tools/sound_streams.py --validate) ---')
    out.append('; Entry $B7 is defined by the table but its pointer ($4010) is never')
    out.append('; followed: its 4 bytes are the note that 17 ptr words target (IDs $00')
    out.append('; $38 $39 $3A $3B $3C $3D $56 $58 $59 $5C $5F $6A $6B $7F $80 $81), so the')
    out.append('; area starts on that row and its $FF terminator lands at $82E0.')
    out.append('SoundCommandStreams:')
    b7 = data[183 * ENTRY_SIZE:183 * ENTRY_SIZE + ENTRY_SIZE]
    body = '  .byte ' + ', '.join('$%02X' % x for x in b7) + ', $FF'
    out.append('%s%s; $82DC  ID $B7  trk 0  ch $00 pulse1   ptr $4010 (unused);'
               ' bytes $82DC-$82E0 are the note end' % (body, ' ' * 3))
    for group in ss.streams(sd):
        desc = group[0]
        if desc['addr'] >= ss.STREAM_B02_END:
            break
        if desc['addr'] + 4 <= STREAM_CPU:
            continue
        desc = dict(desc)
        desc['ids'] = [d['id'] for d in group]
        out.extend(emit_stream(sd, desc, STREAM_CPU, ss.STREAM_B02_END))
    out.append('')
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--write', action='store_true', help='overwrite asm/banks/data_02_sound.asm')
    args = ap.parse_args()
    text = render(read_bank())
    if args.write:
        with open(ASM_PATH, 'w', encoding='utf-8') as f:
            f.write(text)
        print('wrote %s (%d lines)' % (os.path.relpath(ASM_PATH, ROOT), text.count('\n')))
    else:
        print(text)


if __name__ == '__main__':
    main()
