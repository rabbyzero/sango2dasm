#!/usr/bin/env python3
"""Render PRG bank $02 (the Namco-163 sound/note data bank) as annotated asm.

Bank $02 is pure data: it is mapped into the $8000-$9FFF window by SwitchBank8
and read exclusively by B1F_SoundNotePlayer ($E609, fixed bank $1F), which does
`LDY #$22 ; JSR SwitchBank8_B` (Y & $1F = $02) and then loads the 4-byte note
entry at $8000 + soundID*4. See asm/banks/prg_1f.asm and
code/bank_switch_map.md (sections 3, 4.1, 5.2) for the access evidence.

Layout (see code/bank_switch_map.md 5.2 and the SoundNotePlayer field-to-RAM
mapping at $E649-$E661):

  $8000-$82DF  SoundNoteHeaderTable  - 184 x 4-byte note entries (index = soundID)
  $82E0-$9FFF  SoundCommandStreams   - Namco-163 note-sequence command byte streams

The header table is fully understood, so it is emitted as labelled `.byte`
records with the decoded field routing in each comment. The command streams are
not yet decoded per-stream, so they stay as a sliced `.incbin` of
rom/prg/prg_02.bin - the bank still reproduces the ROM byte-for-byte (proven by
tools/verify_data_bank_02.py).

Usage:
    python tools/gen_data_bank_02_asm.py            # preview on stdout
    python tools/gen_data_bank_02_asm.py --write    # update asm/banks/data_02.asm
"""
import argparse
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BANK = 0x02
BANK_BIN = os.path.join('rom', 'prg', 'prg_%02x.bin' % BANK)
ASM_PATH = os.path.join(ROOT, 'asm', 'banks', 'data_%02x.asm' % BANK)

WINDOW_CPU = 0x8000          # bank $02 is only ever mapped into $8000-$9FFF
BANK_SIZE = 0x2000           # 8 KB
ENTRY_SIZE = 4               # header note entry width (SoundNotePlayer: $8000+A*4)
HEADER_CPU = 0x8000          # first note entry
STREAM_CPU = 0x82E0          # command-stream region start (byte alphabet changes)
HEADER_COUNT = (STREAM_CPU - HEADER_CPU) // ENTRY_SIZE   # 184
TRACK_STRIDE = 0x16          # 22-byte sound-RAM track block (SoundInit clear loop)
TRACK_COUNT = 11             # $0700 + 11*22 = $0F2, the SoundInit clear bound
STREAM_PTR_BIAS = 0x40       # entry b3 is stored as (b3 + $40) at $0703


def read_bank():
    with open(os.path.join(ROOT, BANK_BIN), 'rb') as f:
        return f.read()


def fmt_entry(i, b):
    """One 4-byte note entry as a .byte line with the decoded field routing.

    Field meanings come straight from SoundNotePlayer ($E649-$E661):
      b0 -> X : sound-RAM track offset (stride $16)
      b1 -> $0701,X : channel byte (code gates it with CMP #$04)
      b2 -> $0702,X : raw per-note parameter
      b3 -> $0703,X = b3 + $40 (low byte of the note's stream pointer);
              $0700,X <- $00 (marks the track active; $FF = idle sentinel)
    """
    b0, b1, b2, b3 = b
    cpu = HEADER_CPU + i * ENTRY_SIZE
    if b0 % TRACK_STRIDE == 0 and b0 < TRACK_STRIDE * TRACK_COUNT:
        slot = 'slot $%02X trk %d' % (b0, b0 // TRACK_STRIDE)
    else:
        slot = 'slot $%02X' % b0
    return ('  .byte $%02X, $%02X, $%02X, $%02X   ; $%04X  ID $%02X  %s  '
            'ch $%02X  dat $%02X  strm $%02X (+$%02X->$%02X)'
            % (b0, b1, b2, b3, cpu, i, slot, b1, b2, b3, STREAM_PTR_BIAS,
               (b3 + STREAM_PTR_BIAS) & 0xFF))


def render(data):
    out = []
    w = out.append
    w(';===============================================================================')
    w('; DATA Bank 02 (PRG $02) - 8KB sound/note data bank, mapped into $8000-$9FFF by')
    w('; SwitchBank8; no code lives here (see code/bank_switch_map.md 5.2).')
    w(';')
    w('; GENERATED by tools/gen_data_bank_02_asm.py --write; byte-exactness is enforced')
    w('; by tools/verify_data_bank_02.py. Raw source: rom/prg/prg_02.bin (read-only).')
    w(';')
    w('; The ONLY reader is B1F_SoundNotePlayer ($E609, fixed bank $1F):')
    w(';   LDY #$22 ; JSR SwitchBank8_B     (Y & $1F = $02 -> this bank at $8000)')
    w(';   ... reads the 4-byte note entry at $8000 + soundID*4.')
    w('; The wrapper chain B1F_SoundWrapper0..F ($E66B-$E6A5) plays a soundID then')
    w('; falls through with soundID+1, so a fanfare/melody is a contiguous run of')
    w('; header entries. Callers live in banks $1F, $08+$09, $0A+$0B, $17+$18.')
    w(';')
    w('; Regions:')
    w(';   $8000-$82DF  SoundNoteHeaderTable  (%d x 4-byte note entries, index = soundID)'
      % HEADER_COUNT)
    w(';   $82E0-$9FFF  SoundCommandStreams   (%d-byte Namco-163 note-sequence byte streams)'
      % (BANK_SIZE - (STREAM_CPU - WINDOW_CPU)))
    w(';')
    w('; Header note-entry field routing (proven by SoundNotePlayer $E649-$E661):')
    w(';   b0 -> X        sound-RAM track offset (stride $16 = 22 bytes; %d tracks)'
      % TRACK_COUNT)
    w(';   b1 -> $0701,X  channel byte (code gates it with CMP #$04)')
    w(';   b2 -> $0702,X  raw per-note parameter')
    w(';   b3 -> $0703,X  = b3 + $40 ; stream-pointer low byte')
    w(';                  ($0700,X <- $00 marks the track active; $FF = idle sentinel)')
    w(';')
    w('; The command streams are not yet decoded per-stream and stay a sliced')
    w('; .incbin, so this bank always reproduces rom/prg/prg_02.bin exactly.')
    w(';===============================================================================')
    w('')
    w('.segment "CODE_BANK02"')
    w('')
    w('; --- $8000-$82DF  Sound note header table: %d entries x 4 bytes (index = soundID) ---'
      % HEADER_COUNT)
    w('SoundNoteHeaderTable:')
    for i in range(HEADER_COUNT):
        w(fmt_entry(i, data[i * ENTRY_SIZE:i * ENTRY_SIZE + ENTRY_SIZE]))
    w('')
    w('; --- $82E0-$9FFF  Sound command streams: Namco-163 note-sequence byte streams ---')
    w('; NOT ANALYSED per-stream yet - raw slice of rom/prg/prg_02.bin, preserved')
    w('; byte-for-byte. Verify with: python tools/verify_data_bank_02.py')
    w('SoundCommandStreams:')
    w('.incbin "rom/prg/prg_02.bin", $%04X, $%04X'
      % (STREAM_CPU - WINDOW_CPU, BANK_SIZE - (STREAM_CPU - WINDOW_CPU)))
    out.append('')
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--write', action='store_true', help='overwrite asm/banks/data_02.asm')
    args = ap.parse_args()
    text = render(read_bank())
    if args.write:
        with open(ASM_PATH, 'w', encoding='utf-8') as f:
            f.write(text)
        print('wrote %s (%d lines)' % (os.path.relpath(ASM_PATH, ROOT),
                                       text.count('\n')))
    else:
        print(text)


if __name__ == '__main__':
    main()
